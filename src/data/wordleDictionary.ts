export const VALID_WORDLE_GUESSES = new Set<string>([...WORDLE_WORDS, ...EXTRA_VALID_WORDS]);

export function isValidWordleGuess(guess: string) {
  const normalizedGuess = guess
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase();

  return VALID_WORDLE_GUESSES.has(normalizedGuess);
}
